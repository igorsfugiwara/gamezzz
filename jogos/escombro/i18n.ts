const DICIONARIOS: Record<Idioma, Record<Chave, string>> = { pt: PT, en: EN, de: DE };

let atual: Idioma = (() => {
  const l = (navigator.language || 'pt').slice(0, 2).toLowerCase();
  return l === 'de' ? 'de' : l === 'pt' ? 'pt' : 'en';
})();

export function idioma(): Idioma { return atual; }
export function definirIdioma(i: Idioma) { atual = i; document.documentElement.lang = i === 'pt' ? 'pt-BR' : i; }

export function t(chave: Chave, params: Record<string, string | number> = {}): string {
  let s = DICIONARIOS[atual][chave] ?? PT[chave];
  for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Texto em três línguas direto no dado (fases, integrantes, arquivo). */
export type Tri = { pt: string; en: string; de: string };
export const tri = (x: Tri) => x[atual];
