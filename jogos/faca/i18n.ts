import { ler, gravar } from '../compartilhado/salvar';

export type Idioma = 'pt' | 'en';

function idiomaInicial(): Idioma {
  const salvo = ler<Idioma | null>('faca', 'idioma', null);
  if (salvo === 'pt' || salvo === 'en') return salvo;
  try { return /^pt/i.test(navigator.language) ? 'pt' : 'en'; } catch { return 'pt'; }
}

let idioma: Idioma = typeof localStorage === 'undefined' ? 'pt' : idiomaInicial();

export function idiomaAtual(): Idioma { return idioma; }
export function definirIdioma(novo: Idioma) { idioma = novo; gravar('faca', 'idioma', novo); }

